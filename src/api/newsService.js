export const getFeaturedArticles = () => newsItems.filter((item) => item.featured);

export const getArticlesByCategory = (category) => {
  if (!category || category === 'Barchasi') return newsItems;
  return newsItems.filter((item) => item.category === category);
};

export const getArticleBySlug = (slug) => newsItems.find((item) => item.slug === slug);

export const searchArticles = (query = '') => {
  const normalized = query.trim().toLowerCase();
  if (!normalized) return newsItems;

  return newsItems.filter((item) =>
    item.title.toLowerCase().includes(normalized) ||
    item.summary.toLowerCase().includes(normalized) ||
    item.tags.some((tag) => tag.toLowerCase().includes(normalized)) ||
    item.category.toLowerCase().includes(normalized)
  );
};
